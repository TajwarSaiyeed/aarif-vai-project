document.addEventListener("DOMContentLoaded", () => {
  const mainNavigation = document.getElementById("main-navigation");
  const mobileMenuButton = document.getElementById("mobile-menu-button");
  const mobileSidebar = document.getElementById("mobile-sidebar");
  const closeSidebarButton = document.getElementById("close-sidebar-button");
  const sidebarNavigationContent = document.getElementById(
    "sidebar-navigation-content"
  );
  const mobileSearchButton = document.getElementById("mobile-search-button");
  const mobileSearchBar = document.getElementById("mobile-search-bar");

  // Function to build desktop navigation (Mega Menu)
  function buildDesktopNavigation() {
    mainNavigation.innerHTML = ""; // Clear existing content
    navData.forEach((navItem) => {
      // Create the main navigation group
      const groupDiv = document.createElement("div");
      groupDiv.classList.add("group");

      // Create the main navigation link
      const mainLink = document.createElement("a");
      mainLink.href = "#";
      mainLink.classList.add(
        "inline",
        "px-[17px]",
        "pb-[28px]",
        "text-center",
        "no-underline",
        "h-full",
        "text-sm",
        "tracking-[0.3px]",
        "text-[#282c3f]",
        "font-bold",
        "uppercase",
        "relative"
      );
      mainLink.textContent = navItem.name;

      // Create the dynamic hover bar (color uses navItem.color)
      const hoverBar = document.createElement("div");
      hoverBar.classList.add(
        "absolute",
        "left-0",
        "-bottom-[1px]",
        "z-[3]",
        "w-full",
        "h-1",
        `group-hover:bg-[${navItem.color}]`, // Dynamic color
        "transition-all",
        "duration-300"
      );
      mainLink.appendChild(hoverBar);
      groupDiv.appendChild(mainLink);

      // Create the background overlay for desktop mega-menu
      const overlayDiv = document.createElement("div");
      overlayDiv.classList.add(
        "bg-black/30",
        "fixed",
        "z-[-1]",
        "left-0",
        "top-[80px]",
        "invisible",
        "opacity-0",
        "group-hover:visible",
        "group-hover:opacity-100",
        "transition-all",
        "duration-200",
        "w-full",
        "h-full",
        "pointer-events-none"
      );
      groupDiv.appendChild(overlayDiv);

      // Create the mega menu container
      const megaMenuDiv = document.createElement("div");
      megaMenuDiv.classList.add(
        "bg-white",
        "max-w-[1100px]",
        "w-full",
        "h-[500px]",
        "fixed",
        "z-[2]",
        "left-[100px]",
        "top-[80px]",
        "invisible",
        "opacity-0",
        "group-hover:visible",
        "group-hover:opacity-100",
        "transition-all",
        "duration-200",
        "grid",
        "grid-cols-5",
        "shadow-lg",
        "border",
        "border-gray-200",
        "px-5"
      );

      // Populate mega menu columns
      navItem.megaMenuColumns.forEach((column) => {
        const columnDiv = document.createElement("div");
        columnDiv.classList.add("w-full", column.bgClass, "p-4");

        // Add hover effect for columns (optional, replicating original)
        if (column.bgClass === "bg-gray-50") {
          columnDiv.classList.add("hover:bg-gray-100");
        } else if (column.bgClass === "bg-gray-100") {
          columnDiv.classList.add("hover:bg-gray-50");
        }

        column.sections.forEach((section) => {
          const sectionDiv = document.createElement("div");
          // Add common padding/margin classes
          sectionDiv.classList.add("pb-4", "mb-4");
          // Conditionally add border if specified in data
          if (section.borderBottom) {
            sectionDiv.classList.add("border-b", "border-gray-200");
          }

          const heading = document.createElement("h3");
          heading.classList.add(
            "font-bold",
            "text-sm",
            "mb-2",
            `text-[${navItem.color}]` // Dynamic color for headings
          );
          heading.textContent = section.heading;
          sectionDiv.appendChild(heading);

          if (section.items && section.items.length > 0) {
            const ul = document.createElement("ul");
            ul.classList.add(
              "space-y-1",
              "text-xs",
              "text-gray-600",
              "text-[14px]"
            );

            section.items.forEach((item) => {
              const li = document.createElement("li");
              const itemLink = document.createElement("a");
              itemLink.href = item.href;
              itemLink.classList.add(`hover:text-[${navItem.color}]`); // Dynamic color for sub-item hover
              itemLink.textContent = item.text;
              li.appendChild(itemLink);
              ul.appendChild(li);
            });
            sectionDiv.appendChild(ul);
          }
          columnDiv.appendChild(sectionDiv);
        });
        megaMenuDiv.appendChild(columnDiv);
      });

      groupDiv.appendChild(megaMenuDiv);
      mainNavigation.appendChild(groupDiv);
    });
  }

  // Function to build mobile sidebar navigation (Accordion)
  function buildMobileNavigation() {
    sidebarNavigationContent.innerHTML = ""; // Clear existing content

    navData.forEach((navItem) => {
      const accordionItem = document.createElement("div");
      accordionItem.classList.add("border-b", "border-gray-200");

      const accordionHeader = document.createElement("button");
      accordionHeader.classList.add(
        "flex",
        "items-center",
        "justify-between",
        "w-full",
        "p-4",
        "font-bold",
        "text-[#282c3f]",
        "uppercase",
        "text-base",
        "focus:outline-none"
      );
      accordionHeader.innerHTML = `
              <span>${navItem.name}</span>
              <svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide lucide-chevron-down transform transition-transform duration-300">
                <path d="m6 9 6 6 6-6"/>
              </svg>
            `;
      accordionItem.appendChild(accordionHeader);

      const accordionContent = document.createElement("div");
      accordionContent.classList.add(
        "max-h-0",
        "overflow-hidden",
        "transition-all",
        "duration-300",
        "ease-in-out"
      );
      const innerContent = document.createElement("div");
      innerContent.classList.add("p-4", "pt-0", "space-y-4"); // Padding for content

      // Build simplified sub-sections for mobile
      navItem.megaMenuColumns.forEach((column) => {
        column.sections.forEach((section) => {
          const sectionHeading = document.createElement("h4");
          sectionHeading.classList.add(
            "font-bold",
            "text-sm",
            "mb-2",
            `text-[${navItem.color}]` // Dynamic color for mobile headings
          );
          sectionHeading.textContent = section.heading;
          innerContent.appendChild(sectionHeading);

          if (section.items && section.items.length > 0) {
            const ul = document.createElement("ul");
            ul.classList.add("space-y-1", "text-sm", "text-gray-600", "mb-4"); // Add margin-bottom to separate sections
            section.items.forEach((item) => {
              const li = document.createElement("li");
              const itemLink = document.createElement("a");
              itemLink.href = item.href;
              itemLink.classList.add(
                "hover:font-bold",
                `hover:text-[${navItem.color}]` // Dynamic color for mobile sub-item hover
              );
              itemLink.textContent = item.text;
              li.appendChild(itemLink);
              ul.appendChild(li);
            });
            innerContent.appendChild(ul);
          } else {
            // If no items, still add some bottom margin for spacing
            sectionHeading.classList.add("mb-4");
          }
        });
      });

      accordionContent.appendChild(innerContent);
      accordionItem.appendChild(accordionContent);
      sidebarNavigationContent.appendChild(accordionItem);

      accordionHeader.addEventListener("click", () => {
        // Close all other open accordions
        document
          .querySelectorAll("#sidebar-navigation-content .accordion-open")
          .forEach((openContent) => {
            if (openContent !== accordionContent) {
              openContent.style.maxHeight = null;
              openContent.classList.remove("accordion-open");
              openContent.previousElementSibling
                .querySelector("svg")
                .classList.remove("rotate-180");
            }
          });

        // Toggle current accordion
        const isOpen = accordionContent.classList.contains("accordion-open");
        if (isOpen) {
          accordionContent.style.maxHeight = null;
          accordionContent.classList.remove("accordion-open");
          accordionHeader.querySelector("svg").classList.remove("rotate-180");
        } else {
          accordionContent.style.maxHeight =
            accordionContent.scrollHeight + "px";
          accordionContent.classList.add("accordion-open");
          accordionHeader.querySelector("svg").classList.add("rotate-180");
        }
      });
    });

    // --- Add static links below the dynamic categories ---
    const staticLinksContainer = document.createElement("div");
    staticLinksContainer.classList.add(
      "flex",
      "flex-col",
      "px-4",
      "py-2",
      "space-y-3",
      "border-b",
      "border-gray-200"
    );

    const staticLinks = [
      { text: "Orders", href: "#", track: "orders" },
      { text: "Wishlist", href: "#", track: "wishlist" },
      { text: "Gift Cards", href: "#", track: "giftcards" },
      { text: "Contact Us", href: "#", track: "contactus" },
      {
        text: "Myntra Insider",
        href: "#",
        track: "myntrainsider",
        newBadge: true,
      },
    ];

    staticLinks.forEach((linkData) => {
      const link = document.createElement("a");
      link.href = linkData.href;
      link.dataset.track = linkData.track;
      link.classList.add(
        "font-normal",
        "text-sm",
        "text-[#3e4152]",
        "hover:font-bold"
      );
      link.textContent = linkData.text;

      if (linkData.newBadge) {
        const span = document.createElement("span");
        span.classList.add(
          "inline-block",
          "p-px",
          "py-0",
          "bg-[#ff3f6c]",
          "border",
          "border-[#ff3f6c]",
          "text-white",
          "font-black",
          "ml-[10px]",
          "-mt-[6px]",
          "-mb-[10px]",
          "text-[10px]",
          "skew-x-[-10deg]",
          "rounded-sm"
        );
        span.textContent = "New";
        link.appendChild(span);
      }
      staticLinksContainer.appendChild(link);
    });
    sidebarNavigationContent.appendChild(staticLinksContainer);
    // --- End static links section ---
  }

  // Initialize navigations on DOM content loaded
  buildDesktopNavigation();
  buildMobileNavigation();

  // --- Mobile Specific Event Listeners ---

  // Mobile sidebar toggle functionality
  mobileMenuButton.addEventListener("click", () => {
    mobileSidebar.classList.remove("-translate-x-full");
  });

  closeSidebarButton.addEventListener("click", () => {
    mobileSidebar.classList.add("-translate-x-full");
  });

  // Close sidebar when clicking outside (on the overlay)
  mobileSidebar.addEventListener("click", (e) => {
    if (e.target === mobileSidebar) {
      mobileSidebar.classList.add("-translate-x-full");
    }
  });

  // Mobile search bar toggle functionality
  mobileSearchButton.addEventListener("click", () => {
    mobileSearchBar.classList.toggle("hidden");
  });
});
